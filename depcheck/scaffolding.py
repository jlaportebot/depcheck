"""Project scaffolding for depcheck.

Generates a depcheck.yaml configuration file and optional GitHub Actions workflow
using the real config schema from config.py.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class ScaffoldResult:
    """Result of a scaffolding operation."""

    config_path: str
    config_created: bool
    workflow_path: str | None
    workflow_created: bool
    skipped: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        """Convert to dictionary for JSON serialization."""
        return {
            "config_path": self.config_path,
            "config_created": self.config_created,
            "workflow_path": self.workflow_path,
            "workflow_created": self.workflow_created,
            "skipped": self.skipped,
            "warnings": self.warnings,
        }


def _default_workflow_content() -> str:
    """Generate the default GitHub Actions workflow content."""
    return """name: depcheck

on:
  push:
    branches: [main, master]
  pull_request:
    branches: [main, master]
  schedule:
    - cron: '0 6 * * 1'  # Weekly on Monday

jobs:
  depcheck-scan:
    name: Dependency Scan
    runs-on: ubuntu-latest
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4
      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '3.x'
      - name: Install depcheck-cli
        run: pip install depcheck-cli
      - name: Run depcheck scan
        run: depcheck scan --fail-on vulnerable --json

  depcheck-license:
    name: License Check
    runs-on: ubuntu-latest
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4
      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '3.x'
      - name: Install depcheck-cli
        run: pip install depcheck-cli
      - name: Run depcheck license check
        run: depcheck scan --check-licenses --fail-on license --json
"""


def scaffold_project(
    project_path: str | Path, *, workflow: bool = True, force: bool = False
) -> ScaffoldResult:
    """Scaffold a new depcheck project configuration.

    Creates a depcheck.yaml configuration file using the real config schema
    from config.py, and optionally a GitHub Actions workflow file.

    Args:
        project_path: Path to the project directory.
        workflow: Whether to also create a GitHub Actions workflow.
        force: Whether to overwrite existing files.

    Returns:
        A ScaffoldResult with details about what was created or skipped.
    """
    project_path = Path(project_path).resolve()
    result = ScaffoldResult(
        config_path=str(project_path / "depcheck.yaml"),
        config_created=False,
        workflow_path=None,
        workflow_created=False,
    )

    # Handle config file
    config_path = project_path / "depcheck.yaml"
    if config_path.exists() and not force:
        result.skipped.append("depcheck.yaml")
        result.warnings.append(f"Config file already exists: {config_path}")
    else:
        config_content = _generate_yaml_config(project_path)
        config_path.write_text(config_content, encoding="utf-8")
        result.config_created = True

    # Handle workflow file
    if workflow:
        workflow_path = project_path / ".github" / "workflows" / "depcheck.yml"
        result.workflow_path = str(workflow_path)

        if workflow_path.exists() and not force:
            result.skipped.append("depcheck.yml")
            result.warnings.append(f"Workflow file already exists: {workflow_path}")
        else:
            workflow_path.parent.mkdir(parents=True, exist_ok=True)
            workflow_content = _default_workflow_content()
            workflow_path.write_text(workflow_content, encoding="utf-8")
            result.workflow_created = True

    return result


def _generate_yaml_config(project_path: Path) -> str:
    """Generate a depcheck.yaml configuration using the real config schema."""
    # Use the actual defaults from the Config classes
    lines = [
        "# depcheck configuration",
        "# Generated by depcheck scaffold",
        "",
        "scan:",
        "  check_vulnerabilities: true",
        "  check_licenses: false",
        '  allowed_license_categories: ["permissive", "public_domain"]',
        "  denied_licenses: []",
        "  fail_on: null",
        "  quiet: false",
        "  output_json: false",
        "",
        "budget:",
        "  total: null",
        "  direct: null",
        "  transitive: null",
        "  dev: null",
        "  optional: null",
        "  groups: {}",
        "",
        "policy:",
        "  rules: []",
        "",
    ]
    return "\n".join(lines) + "\n"


def render_scaffold_markdown(result: ScaffoldResult) -> str:
    """Render a ScaffoldResult as a Markdown summary.

    Args:
        result: The scaffold result to render.

    Returns:
        A Markdown-formatted string summarizing the scaffold operation.
    """
    lines = ["# depcheck Scaffold Summary", ""]

    if result.config_created:
        lines.append("- ✅ **Created:** `depcheck.yaml`")
    elif "depcheck.yaml" in " ".join(result.skipped):
        lines.append("- ⏭️ **Skipped:** `depcheck.yaml` (already exists)")

    if result.workflow_path:
        workflow_rel = Path(result.workflow_path).name
        if result.workflow_created:
            lines.append("- ✅ **Created:** `.github/workflows/depcheck.yml`")
        elif workflow_rel in " ".join(result.skipped):
            lines.append("- ⏭️ **Skipped:** `.github/workflows/depcheck.yml` (already exists)")

    if result.skipped:
        lines.append("")
        lines.append("## Skipped Files")
        lines.append("")
        for skipped in result.skipped:
            lines.append(f"- `{skipped}`")

    if result.warnings:
        lines.append("")
        lines.append("## Warnings")
        lines.append("")
        for warning in result.warnings:
            lines.append(f"- {warning}")

    return "\n".join(lines)
